#!/usr/bin/env python3
"""Convert a sized sky130 subckt (xschem netlist) into a MAGICAL mock-PDK example folder.

usage: python3 scripts/make_magical_input.py <sized.spice> <out_dir> --name ota5t
MAGICAL reads Spectre syntax and recognises devices only by the names nch/pch (flow/python/DesignDB.py),
so sky130_fd_pr__nfet_01v8 -> nch and sky130_fd_pr__pfet_01v8 -> pch. W/L/nf are kept as given.
IMPORTANT: the mock PDK is not SKY130; results are for flow/algorithm study only.
Ideal voltage sources are removed and their node becomes a port (same rule as make_align_input.py).
"""
import argparse, json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from make_align_input import parse  # same parser

MAP = {"sky130_fd_pr__nfet_01v8": "nch", "sky130_fd_pr__pfet_01v8": "pch"}

ap = argparse.ArgumentParser(); ap.add_argument("sized_spice"); ap.add_argument("out_dir"); ap.add_argument("--name", default="ota5t")
ap.add_argument("--bias-port", default="VBIAS")
a = ap.parse_args()
_, ports, devs, srcs = parse(Path(a.sized_spice))
ren = {s["p"]: a.bias_port for s in srcs}
ports = [p for p in ports] + [a.bias_port for _ in srcs]
out = Path(a.out_dir); out.mkdir(parents=True, exist_ok=True)
L = ["// generated by scripts/make_magical_input.py from " + a.sized_spice,
     "// MOCK PDK MAPPING: sky130 nfet/pfet -> nch/pch (not SKY130 geometry)",
     f"topckt {a.name} " + " ".join(ports)]
for d in devs:
    nets = [ren.get(d[t], d[t]) for t in ("d", "g", "s", "b")]
    L.append(f"{d['ref_name'].lstrip('X')} ({' '.join(nets)}) {MAP[d['model']]} l={d['L_um']*1000:g}n w={d['W_um']:g}u m={d['m']} nf={d['nf']}")
L.append(f"ends {a.name}")
(out / f"{a.name}.sp").write_text("\n".join(L) + "\n")
(out / f"{a.name}.json").write_text(json.dumps({
    "spectre_netlist": f"{a.name}.sp", "resultDir": "./",
    "techfile": "../mockPDK/mock.techfile", "simple_tech_file": "../mockPDK/techfile.simple",
    "lef": "../mockPDK/mock.lef"}, indent=4) + "\n")
(out / "run.sh").write_text(f"mkdir -p gds\npython ../../flow/python/Magical.py {a.name}.json\n")
print((out / f"{a.name}.sp").read_text())
