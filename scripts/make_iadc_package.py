#!/usr/bin/env python3
"""Design package for the iadc fully differential folded-cascode OTA (github.com/r09g/iadc, MIT; vendored
read-only in circuits/iadc_ota/upstream_src/).

Upstream has: the OTA netlist (folded_cascode_3_core + folded_cascode_3_bias + a switched-capacitor CMFB),
the hand-drawn Magic layout with its LVS and PEX netlists, and transient testbenches (30 uA bias current,
0.3 pF loads, 5.1 MHz clocks). It has no AC testbench of the final OTA, no specs and no performance figures
for the OTA.

AC model used here (ASSUMPTION, documented in SOURCE.md): the switched-capacitor CMFB cannot be analysed in
AC. In differential mode its node cmc does not move, so the DUT is core + bias + the CMFB's two output
capacitors C3/C4 (op-cmc, on-cmc), which do load the outputs in differential mode; the switches and their
capacitors only touch cmc. The CMFB itself is replaced in the testbench wrapper by an ideal source with
the SC CMFB's steady-state law  v(cmc) = v(bias_a) + (v(op) + v(on))/2 - v(cm)  (cm is generated by the
bias block). The 30 uA bias current is an ideal source inside the DUT (bias_sources).

    source scripts/env.sh && python3 scripts/make_iadc_package.py
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "scripts"))
import benchlib  # noqa: E402
import flatten_spice  # noqa: E402
import recognize_structures as rs  # noqa: E402
from src.common import spice  # noqa: E402

DESIGN = "iadc_ota"
BASE = REPO / "circuits" / DESIGN
UP = BASE / "upstream_src"
WORK = REPO / "runs" / "tmp" / f"{DESIGN}_pkg"
IBIAS_A = 30e-6     # I1 in verification/schematic_sim/ota_tb_tran_ideal_clock.sch
CL = "0.3p"         # C1/C5 in the same testbench
CONDITIONS = {"VDD_V": 1.8, "VCM_V": 0.9, "CL_F": CL, "temp": 27, "corner": "tt"}

TOP = f"""
.subckt {DESIGN}_top ip in op on VDD VSS cmc cm bias_a
x1 bias_a bias_b bias_c bias_d cm i_bias VDD VSS folded_cascode_3_bias
x2 cmc ip in bias_a bias_b bias_c bias_d op on VDD VSS folded_cascode_3_core
XC3 op cmc sky130_fd_pr__cap_mim_m3_1 W=4.8 L=4.8 MF=4 m=4
XC4 on cmc sky130_fd_pr__cap_mim_m3_1 W=4.8 L=4.8 MF=4 m=4
XM43 VDD VDD VDD VDD sky130_fd_pr__pfet_01v8_lvt L=0.6 W=1.4 nf=1 ad='int((nf+1)/2) * W/nf * 0.29' as='int((nf+2)/2) * W/nf * 0.29' pd='2*int((nf+1)/2) * (W/nf + 0.29)' ps='2*int((nf+2)/2) * (W/nf + 0.29)' nrd='0.29 / W' nrs='0.29 / W' sa=0 sb=0 sd=0 mult=8 m=8
XM45 VDD VDD VDD VDD sky130_fd_pr__pfet_01v8 L=0.6 W=1.4 nf=1 ad='int((nf+1)/2) * W/nf * 0.29' as='int((nf+2)/2) * W/nf * 0.29' pd='2*int((nf+1)/2) * (W/nf + 0.29)' ps='2*int((nf+2)/2) * (W/nf + 0.29)' nrd='0.29 / W' nrs='0.29 / W' sa=0 sb=0 sd=0 mult=6 m=6
XM9 VSS VSS VSS VSS sky130_fd_pr__nfet_01v8 L=0.6 W=1.4 nf=1 ad='int((nf+1)/2) * W/nf * 0.29' as='int((nf+2)/2) * W/nf * 0.29' pd='2*int((nf+1)/2) * (W/nf + 0.29)' ps='2*int((nf+2)/2) * (W/nf + 0.29)' nrd='0.29 / W' nrs='0.29 / W' sa=0 sb=0 sd=0 mult=23 m=23
.ends
"""


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> int:
    WORK.mkdir(parents=True, exist_ok=True)
    for sub in ("source", "testbenches", "upstream"):
        (BASE / sub).mkdir(parents=True, exist_ok=True)
    src = WORK / "ota_with_ac_top.spice"
    src.write_text((UP / "netlist" / "ota.spice").read_text() + TOP)
    flat = WORK / "flat.spice"
    stats = flatten_spice.flatten(src, f"{DESIGN}_top", flat, DESIGN)
    lines = flat.read_text().splitlines()
    out = []
    for ln in lines:
        if ln.startswith(".ends"):
            out.append("* bias current of the upstream testbench (ota_tb_tran_ideal_clock: I1 = 30 uA), bias_sources")
            out.append(f"Ibias_ext VDD i_bias {IBIAS_A:g}")
        out.append(ln)
    dut = "\n".join(out) + "\n"
    (BASE / "source" / f"{DESIGN}.spice").write_text(dut + ".end\n")
    nl = spice.parse(BASE / "source" / f"{DESIGN}.spice")
    std = {"ip": "INP", "in": "INN", "op": "OUTP", "on": "OUTN", "VDD": "VDD", "VSS": "VSS",
           "cmc": "cmc_w", "cm": "cm_w", "bias_a": "bias_a_w"}
    xdut = "XDUT " + " ".join(std[p] for p in nl.ports) + f" {DESIGN}"
    wrapper = ("* ideal CMFB: the steady-state law of the upstream switched-capacitor CMFB (ASSUMPTION)\n"
               "Bcmfb cmc_w VSS V = v(bias_a_w) + (v(OUTP) + v(OUTN))/2 - v(cm_w)\n")
    dut_sub = re.search(rf"^\.subckt {DESIGN}.*?^\.ends {DESIGN}\n", dut, re.S | re.M).group(0)
    for kind in ("AC", "OP", "NOISE"):
        (BASE / "testbenches" / f"dido_amp_{kind}.spice").write_text(
            benchlib.bench(DESIGN, kind, dut_sub, xdut, differential_output=True, wrapper_extra=wrapper))

    cfg = {
        "name": DESIGN,
        "description": "Fully differential folded-cascode OTA of the iadc incremental delta-sigma modulator "
                       "(unit transistors 1.4/0.6 um, dummies), AC model with an ideal CMFB.",
        "interface": {"input": "differential", "output": "differential", "kind": "amp", "dut_symbol": "dut_amp",
                      "ports": {"INP": "ip", "INN": "in", "OUTP": "op", "OUTN": "on", "VDD": "VDD", "VSS": "VSS"}},
        "analyses": ["AC", "OP", "NOISE"],
        "conditions": CONDITIONS,
        "specs": {"pm_deg": {"min": 60}},
        "spec_notes": {"ASSUMPTION": "upstream gives no OTA specs or figures. gain_db and gbw_mhz from this flow's own "
                                     "simulation by the package rule (gain -1 dB, GBW x 0.9); PM >= 60 deg."},
    }
    (BASE / "source" / "config.yaml").write_text("# Generated by scripts/make_iadc_package.py. Specs: ASSUMPTION.\n" +
                                                 yaml.safe_dump(cfg, sort_keys=False))
    rails = {"VDD", "VSS"}
    prim = rs.to_primitives(rs.recognize(nl, rails), nl, DESIGN)
    up = BASE / "upstream"
    (up / "primitives.json").write_text(json.dumps(prim, indent=1) + "\n")
    groups: dict = {}
    for e in [m.name for m in nl.mosfets] + [p.name for p in nl.passives]:
        m = re.match(r"^X(X\d+)_", e)
        groups.setdefault(m.group(1).lower() if m else "top", []).append(e)
    (up / "hierarchy.json").write_text(json.dumps({
        "design": DESIGN, "provenance": "upstream netlist hierarchy (real), read from the flat instance names",
        "root": {"level": 2, "kind": "differential-input-differential-output-amplifier", "subckt": DESIGN},
        "levels": [{"level": 1, "top": [{"instance": k, "kind": {"x1": "folded_cascode_3_bias", "x2": "folded_cascode_3_core",
                                                                 "top": "CMFB output capacitors C3/C4, top-level dummies"}.get(k, k),
                                         "elements": sorted(v)} for k, v in sorted(groups.items())]}]}, indent=1) + "\n")
    (up / "name_map.yaml").write_text(yaml.safe_dump({
        "upstream_design": DESIGN, "target_design": DESIGN, "devices": {m.name: m.name for m in nl.mosfets},
        "nets": {n: n for n in sorted(nl.nets())},
        "manual": ["Identity map: the predicted primitives were recognised on this same flat netlist."]}, sort_keys=False))
    eq = {
        "design": DESIGN, "mode": "differential", "provenance": "PREDICTED",
        "assumes": "purely differential drive; single-stage folded cascode; output resistance by gm*ro*ro on both sides; "
                   "non-dominant pole at the folding node; CMFB inactive in differential mode",
        "source": "textbook folded-cascode OTA (Johns & Martin, 2nd ed., sec. 6.4; Razavi, 2nd ed., sec. 9.4)",
        "performance": {
            "circuit": DESIGN, "input": "vd", "output": "v(op) - v(on)", "load": {"CL": "each output to GND"},
            "terms": {
                "gm1": "G1_XX2_M1",
                "rup": "G1_XX2_M8*R1_XX2_M8*(R1_XX2_M12*R1_XX2_M2/(R1_XX2_M12 + R1_XX2_M2))",
                "rdn": "G1_XX2_M7*R1_XX2_M7*R1_XX2_M4",
                "Ro": "rup*rdn/(rup + rdn)",
                "Cout": "CL + C_XC3 + C4_XX2_M8 + C4_XX2_M7 + C3_XX2_M8 + C3_XX2_M7",
                "Cf": "C2_XX2_M8 + C4_XX2_M12 + C4_XX2_M2 + C3_XX2_M2 + C3_XX2_M12",
                "A0": "gm1*Ro",
                "wgbw": "gm1/Cout",
                "wp2": "G1_XX2_M8/Cf",
                "wu": "wgbw",
            },
            "gain_db": "20*log(Abs(A0))/log(10)",
            "gbw_mhz": "wu/(2000000*pi)",
            "pm_deg": "180 - 180*(atan(wu*Ro*Cout) + atan(wu/wp2))/pi",
        },
    }
    (up / "equations.predicted.json").write_text(json.dumps(eq, indent=1) + "\n")
    files = [BASE / "source" / f"{DESIGN}.spice", BASE / "source" / "config.yaml"] + \
            sorted((BASE / "testbenches").glob("*.spice")) + sorted(up.glob("*"))
    commit = (UP / "UPSTREAM_COMMIT.txt").read_text().strip()
    (BASE / "SOURCE.md").write_text(f"""# {DESIGN}: provenance

Generated {dt.date.today().isoformat()} by `scripts/make_iadc_package.py` from `upstream_src/` (r09g/iadc, commit {commit}, MIT).

| Item | Origin | Status |
|---|---|---|
| Core and bias | `netlist/ota.spice`: folded_cascode_3_core, folded_cascode_3_bias, top-level dummies; flattened ({stats['devices']} devices) | copied, flattened |
| CMFB | switched-capacitor CMFB: its output capacitors C3/C4 kept; the switches and C1/C2/C5/C6 removed; an ideal CMFB with the SC steady-state law in the testbench wrapper | **ASSUMPTION** (AC model) |
| Bias current | 30 uA ideal source inside the DUT (`Ibias_ext`, bias_sources), from ota_tb_tran_ideal_clock | adapted |
| Load | 0.3 pF per output, from the same testbench | copied |
| Testbenches | `dido_amp_AC/OP/NOISE` (scripts/benchlib.py) | **new** |
| Specs | `config.yaml`: **ASSUMPTION**; upstream gives none | **new** |
| Primitives | rule-based recognition | **PREDICTED** |
| Symbolic equations | textbook folded-cascode model | **PREDICTED** |
| Layout reference | `upstream_src/layout/ota/` (hand-drawn Magic layout), `upstream_src/netlist/ota_layout_pex.spice` | copied |

SHA-256 of the generated files:
""" + "".join(f"- `{f.relative_to(BASE)}` {sha(f)}\n" for f in files))
    print("devices:", stats)
    print("wrote", BASE.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
